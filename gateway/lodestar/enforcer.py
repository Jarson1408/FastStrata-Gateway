"""LODESTAR tool-call enforcer - silent block + todo enforcement (no echo hack).

The previous implementation rewrote unauthorized tool calls to
`echo "Error: LODESTAR state X is incomplete..."`. That caused JSON parse
errors in the OpenCode client because the original call and the synthesized
bash call were concatenated in the message history.

This version returns one of four verdicts; the caller (app.py) is responsible
for actually dropping the event, injecting a reminder SSE chunk, or
injecting a "next required action" prompt.

State policy (v2.2, after Capacitor_charging 2026-07-07 hijack incident):

  READ   (1) -> only read of active-context.md and `bash embed.py search` allowed.
                  NO skills: loading a skill here hijacks the model and makes
                  it forget about LODESTAR (the 2026-07-07 failure mode).
  UPDATE (2) -> edit of active-context.md, read of active-context or skill files,
                  but NOT skill/load_skill tool calls. Skills are deferred to
                  state 3 so the model commits to a Goal in active-context first.
  READY  (3) -> all tools allowed. The active-context.md is the source of truth
                  for the current task; skill loading and execution happen here.

Forced order (v2.4, after 2026-07-07 21:57 skill-skipped-then-write incident):

  If a `LodestarTodo` is provided AND a required action is pending AND the
  call is NOT the one that completes the required action, the enforcer
  returns INJECT_TODO with a "do this first" prompt. This forces the
  model to do required LODESTAR steps in order rather than skipping ahead.

Hallucinated tool protection: if `registered_tools` is provided (the set of tool
names the OpenCode client sent in this request), any tool call to a name NOT in
the set is dropped. This prevents models from calling tools that don't exist
(e.g. the `question` tool the brainstorming skill tried to use in the 2026-07-07
session, which is not registered in OpenCode).
"""
from __future__ import annotations

from enum import Enum
from typing import TYPE_CHECKING

from gateway.lodestar.idempotency import IdempotencyResult
from gateway.lodestar.state import LodestarState

if TYPE_CHECKING:
    from gateway.lodestar.todo import LodestarTodo
from gateway.lodestar.tool_names import (
    READ_TOOLS as _READ_TOOLS,
    EDIT_TOOLS as _EDIT_TOOLS,
    SHELL_TOOLS as _SHELL_TOOLS,
    SKILL_TOOLS as _SKILL_TOOLS,
    PATH_KEYS as _PATH_KEYS,
    CMD_KEYS as _CMD_KEYS,
    ACTIVE_CONTEXT as _ACTIVE_CONTEXT,
    get_path as _get_path,
    get_cmd as _get_cmd,
    is_active_context_path as _is_active_context_path,
)


class EnforceResult(str, Enum):
    ALLOW = "allow"
    DROP = "drop"
    INJECT_REMINDER = "inject_reminder"
    INJECT_TODO = "inject_todo"


_SKILL_FILE_SUFFIX = "skill.md"


def _is_skill_file_path(params: dict) -> bool:
    path = _get_path(params)
    return path.endswith(_SKILL_FILE_SUFFIX) or "skill" in path


def enforce_tool_call(
    name: str,
    params: dict,
    state: LodestarState,
    idempotency_result: IdempotencyResult | None = None,
    registered_tools: frozenset[str] | set[str] | None = None,
    todo: "LodestarTodo | None" = None,
) -> EnforceResult:
    """Return ALLOW / DROP / INJECT_REMINDER / INJECT_TODO for the given tool call.

    Args:
      name: tool name as generated by the model (case-insensitive match).
      params: tool call arguments dict.
      state: current LODESTAR state.
      idempotency_result: if the call is an active-context edit, pass the
        IdempotencyResult so we can return INJECT_REMINDER instead of allowing
        a redundant edit.
      registered_tools: optional set of tool names registered by the OpenCode
        client for this request. If provided, any tool call to a name NOT in
        this set is dropped (rejects hallucinated tool calls).
      todo: optional LodestarTodo that tracks per-state required actions. If
        provided AND a required action is pending AND the call is not the
        one that completes it, return INJECT_TODO. This enforces the
        required sequence (e.g. "read active-context BEFORE running embed search").
    """
    # Hallucinated-tool check: runs first so it overrides everything else.
    if registered_tools is not None and name not in registered_tools:
        return EnforceResult.DROP

    # Todo check: if a required action is pending and this call is not
    # the one that completes it, force the model to do the required action
    # first. Runs BEFORE state-based checks because v2.4 forced-order is
    # more specific than v2.2 state policy.
    if todo is not None and todo.is_blocking(name, params):
        return EnforceResult.INJECT_TODO

    if state >= LodestarState.READY:
        return EnforceResult.ALLOW

    name_l = name.lower()

    if state == LodestarState.READ:
        if name_l in _READ_TOOLS and _is_active_context_path(params):
            return EnforceResult.ALLOW
        if name_l in _SHELL_TOOLS and "embed.py" in _get_cmd(params) and " search " in f" {_get_cmd(params)} ":
            return EnforceResult.ALLOW
        return EnforceResult.DROP

    # state == UPDATE
    # Note: skills are NOT allowed in UPDATE anymore. They are deferred to READY
    # so the model commits a Goal in active-context.md before consuming skill
    # instructions. This is the v2.2 fix for the 2026-07-07 Capacitor session
    # where the model loaded brainstorming in state 2 and forgot to write
    # active-context.md.
    if name_l in _EDIT_TOOLS:
        if _is_active_context_path(params):
            if idempotency_result is not None and not idempotency_result.is_modified:
                return EnforceResult.INJECT_REMINDER
            return EnforceResult.ALLOW
        return EnforceResult.DROP
    if name_l in _READ_TOOLS:
        if _is_active_context_path(params) or _is_skill_file_path(params):
            return EnforceResult.ALLOW
        return EnforceResult.DROP
    if name_l in _SKILL_TOOLS:
        # Skills must wait for state 3 (READY).
        return EnforceResult.DROP
    return EnforceResult.DROP
